          </style>
          <div class="bh-unified-layout">
            <nav class="bh-unified-nav" aria-label="Leader portal navigation"><strong>Leader Hub</strong>
              <?php foreach ( $links as $link ) : ?>
                <a href="<?php echo esc_url( $link[1] ); ?>" <?php if ( $pages[ $tag ] === $link[2] && ( $tag !== 'bh_leader_edit_activity' || $link[0] === 'Edit activity' ) ) : ?>aria-current="page"<?php endif; ?>><?php echo esc_html( $link[0] ); ?></a>
              <?php endforeach; ?>
            </nav>
            <main class="bh-unified-content"><?php echo $output; // Shortcode HTML generated by trusted portal renderers. ?></main>
